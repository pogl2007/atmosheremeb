// Формы сайта собирают имя и телефон, и без этих двух документов это прямое
// нарушение 152-ФЗ: оператор обязан опубликовать политику (ст. 18.1),
// а с 1 сентября 2025 года согласие оформляется отдельным документом,
// а не строчкой под кнопкой (ст. 9).
//
// Тексты описывают то, что сайт делает на самом деле: какие поля принимает
// бекенд (backend/api.go), куда их отправляет и где хранит. Меняется
// обработка — меняйте и текст здесь.
//
// ВНИМАНИЕ. Это рабочая основа, а не заключение юриста. Перед запуском
