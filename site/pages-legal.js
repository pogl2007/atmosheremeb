// (pd.rkn.gov.ru). Реквизиты оператора подставятся из site/contacts.js,
// когда там будут заполнены поля и снят тестовый режим.

const { page, КОНТАКТЫ } = require('./layout.js');
const { esc } = require('./pages.js');

const К = КОНТАКТЫ;

// Кто оператор. Пока реквизитов нет — честная пометка вместо выдуманного ИП.
function оператор() {
  if (К.тестовыйРежим || !К.legalName) {
    return `<span class="stub">реквизиты оператора будут указаны после регистрации</span>`;
  }
  return `${esc(К.legalName)}, ИНН ${esc(К.inn)}, ОГРНИП ${esc(К.ogrnip)}, адрес: ${esc(К.address)}`;
}

// Как отозвать согласие или задать вопрос
function связь() {
  if (К.email) return `по электронной почте <a href="mailto:${esc(К.email)}">${esc(К.email)}</a>`;
  return 'через форму обратной связи на странице <a href="/contacts/">«Контакты»</a>';
}

const ПОМЕТКА_ТЕСТА = () => К.тестовыйРежим ? `
  <div class="test-note">
    <b>${esc(К.надписьТест)}</b>
    <p>Реквизиты оператора появятся в документе после запуска сайта.</p>
  </div>` : '';

