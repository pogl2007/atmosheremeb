// Справка должна находить то, о чём спросили, и молчать, когда ничего похожего нет
func TestСправка(t *testing.T) {
	папка := t.TempDir()
	данные := знания{
		Товары: []ТоварЗнаний{
			{Имя: "Дюна", Раздел: "Кухни", Адрес: "/product/dyuna/", Планировка: "П-образная",
				Стиль: "минимализм", Гамма: "светлая", Состав: []string{"столешница под камень"},
				Кратко: "П-образная кухня в песочных тонах", Описание: "Матовые песочные фасады и деревянные рейки."},
			{Имя: "Пергамент", Раздел: "Шкафы и гардеробные", Адрес: "/product/pergament/", Планировка: "купе",
				Стиль: "современная", Гамма: "светлая", Состав: []string{"двери-купе", "зеркало"},
				Кратко: "Светлый шкаф-купе с зеркалом", Описание: "Полотна с зеркальными вставками во всю стену."},
		},
		Статьи: []КусокСтатьи{{
			Статья: "Фасады для кухни", Раздел: "ЛДСП", Адрес: "/blog/fasady/",
			Текст: "ЛДСП — ламинированная древесностружечная плита, из неё делают корпус и бюджетные фасады кухни. " +
				"Слабое место — кромка: если она плохо приклеена, влага попадает внутрь и плита разбухает.",
		}},
	}
	сырое, _ := json.Marshal(данные)
	if err := os.WriteFile(filepath.Join(папка, ФайлЗнаний), сырое, 0o600); err != nil {
		t.Fatal(err)
	}

	б := открытьБазу(папка, nil)

	проверки := []struct {
		вопрос string
		ждём   string
	}{
		{"Какие кухни у вас есть?", "Дюна"},
		// Раздел назван прямо — чужие разделы в справку не попадают
		{"покажите кухни", "Кухни"},
		{"нужен шкаф-купе с зеркалом", "Пергамент"},
		{"что такое ЛДСП", "ламинированная"},
	}
	for _, п := range проверки {
		справка, _ := б.Справка(п.вопрос, nil)
		if !strings.Contains(справка, п.ждём) {
			t.Errorf("«%s»: в справке нет %q, получено: %s", п.вопрос, п.ждём, обрезать(справка, 200))
		}
	}

	// Вопрос не про мебель — справку не навязываем
	if справка, _ := б.Справка("какая сегодня погода в Москве", nil); справка != "" {
		t.Errorf("на посторонний вопрос подставилась справка: %s", обрезать(справка, 200))
	}
}

func TestОснова(t *testing.T) {
	пары := map[string]string{"кухни": "кухн", "кухня": "кухн", "кухнями": "кухн", "шкафы": "шкаф", "шкаф": "шкаф"}
	for слово, ждём := range пары {
		if о := основа(слово); о != ждём {
			t.Errorf("основа(%q) = %q, ждали %q", слово, о, ждём)
		}
	}
}

// Вопрос про кухни не должен тянуть шкафы и наоборот
func TestРазделВопроса(t *testing.T) {
	пары := map[string]string{
		"что за кухни у вас есть":   "Кухни",
		"нужен шкаф-купе":           "Шкафы и гардеробные",
		"мебель в прихожую":         "Прихожие",
		"сколько стоит доставка":    "",
	}
	for вопрос, ждём := range пары {
		if р := разделВопроса(вопрос); р != ждём {
			t.Errorf("«%s» → %q, ждали %q", вопрос, р, ждём)
		}
	}
}

// Короткое согласие — не повод подставлять каталог заново
func TestСогласие(t *testing.T) {
	согласие := []string{"да", "Давай", "давайте", "хорошо", "ок", "пусть приедет", "да, давайте"}
	для := []string{"да, а сколько стоит кухня", "давай посчитаем шкаф 3 метра", "хорошо, но нужна кухня побольше"}
	for _, в := range согласие {
		if !этоСогласие(в) {
			t.Errorf("«%s» должно считаться согласием", в)
		}
	}
	for _, в := range для {
		if этоСогласие(в) {
			t.Errorf("«%s» — это вопрос, а не согласие", в)
		}
	}
}
