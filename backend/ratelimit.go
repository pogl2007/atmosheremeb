package main

// Ограничитель частоты запросов.
//
// В версии на PHP счётчики лежали файлами во временной папке: каждый процесс
// открывал файл, брал блокировку, читал, писал и закрывал. Здесь сервер —
// один долгоживущий процесс, поэтому счётчики просто живут в памяти.
// Это быстрее и, что важнее, не оставляет на диске следов вида
// «хеш IP-адреса посетителя» — то есть меньше персональных данных.

import (
	"sync"
	"time"
)

type Ограничитель struct {
	предел int
	окно   time.Duration

	замок  sync.Mutex
	отметки map[string][]time.Time
}

func новыйОграничитель(предел int, окно time.Duration) *Ограничитель {
	о := &Ограничитель{предел: предел, окно: окно, отметки: map[string][]time.Time{}}
	go о.убирать()
	return о
}

// Возвращает true, если запрос надо отклонить.
func (о *Ограничитель) превышен(ключ string) bool {
	о.замок.Lock()
	defer о.замок.Unlock()

	теперь := time.Now()
	граница := теперь.Add(-о.окно)

	свежие := о.отметки[ключ][:0]
	for _, т := range о.отметки[ключ] {
		if т.After(граница) {
			свежие = append(свежие, т)
		}
	}
	свежие = append(свежие, теперь)
	о.отметки[ключ] = свежие

	return len(свежие) > о.предел
}

// Раз в десять минут выкидываем адреса, о которых давно ничего не слышно.
// Без этого карта росла бы вечно: каждый сканер оставлял бы в ней запись.
func (о *Ограничитель) убирать() {
	for range time.Tick(10 * time.Minute) {
		о.замок.Lock()
		граница := time.Now().Add(-о.окно)
		for ключ, отметки := range о.отметки {
			живые := false
			for _, т := range отметки {
				if т.After(граница) {
					живые = true
					break
				}
			}
			if !живые {
				delete(о.отметки, ключ)
			}
		}
		о.замок.Unlock()
	}
}
