// Подставной векторизатор: вектор зависит от того, какие темы встретились
// в тексте. Этого достаточно, чтобы проверить кэш, косинус и слияние,
// не обращаясь к платному сервису.
type игрушечныеВекторы struct{ вызовов int }

func (в *игрушечныеВекторы) Имя() string { return "игрушка" }

func (в *игрушечныеВекторы) Векторы(_ context.Context, тексты []string) ([][]float32, error) {
	в.вызовов++
	темы := []string{"кухн", "шкаф", "спальн"}
	из := make([][]float32, len(тексты))
	for i, т := range тексты {
		н := strings.ToLower(т)
		вектор := make([]float32, len(темы))
		for j, тема := range темы {
			if strings.Contains(н, тема) {
				вектор[j] = 1
			}
		}
		// «готовка» — про кухню, хотя слова «кухня» в тексте нет:
		// ровно тот случай, ради которого нужны векторы
		if strings.Contains(н, "готов") {
			вектор[0] = 1
		}
		из[i] = нормировать(вектор)
	}
	return из, nil
}

func базаДляПоиска(t *testing.T, в Векторизатор) (*База, string) {
	t.Helper()
	папка := t.TempDir()
	данные := знания{Товары: []ТоварЗнаний{
		{Имя: "Дюна", Раздел: "Кухни", Адрес: "/product/dyuna/", Планировка: "П-образная",
			Стиль: "минимализм", Гамма: "светлая", Кратко: "П-образная кухня в песочных тонах",
			Описание: "Матовые песочные фасады, столешница под камень."},
		{Имя: "Пергамент", Раздел: "Шкафы и гардеробные", Адрес: "/product/pergament/", Планировка: "купе",
			Стиль: "современная", Гамма: "светлая", Кратко: "Светлый шкаф-купе с зеркалом",
			Описание: "Полотна с зеркальными вставками во всю стену."},
	}}
	сырое, _ := json.Marshal(данные)
	if err := os.WriteFile(filepath.Join(папка, ФайлЗнаний), сырое, 0o600); err != nil {
		t.Fatal(err)
	}
	return открытьБазу(папка, в), папка
}

// Вопрос без слова «кухня» словарный поиск не берёт, а векторный — да
func TestВекторыНаходятПоСмыслу(t *testing.T) {
	игрушка := &игрушечныеВекторы{}
	б, _ := базаДляПоиска(t, игрушка)
	if !б.своиВекторы {
		t.Fatal("векторы записей не посчитались")
	}
	справка, сколько := б.Справка("мебель для готовки", nil)
	if сколько == 0 || !strings.Contains(справка, "Дюна") {
		t.Fatalf("по смыслу ничего не нашлось: %q", обрезать(справка, 200))
	}
	if strings.Contains(справка, "Пергамент") {
		t.Errorf("в выдачу попал шкаф: %q", обрезать(справка, 200))
	}
}

// Векторы считаются один раз и дальше читаются из файла
func TestВекторыКэшируются(t *testing.T) {
	игрушка := &игрушечныеВекторы{}
	_, папка := базаДляПоиска(t, игрушка)
	послеПервой := игрушка.вызовов

	сырое, err := os.ReadFile(filepath.Join(папка, ФайлВекторов))
	if err != nil {
		t.Fatalf("файл векторов не создан: %v", err)
	}
	var кэш кэшВекторов
	if json.Unmarshal(сырое, &кэш) != nil || len(кэш.Векторы) != 2 {
		t.Fatalf("в кэше не те данные: %s", обрезать(string(сырое), 120))
	}

	открытьБазу(папка, игрушка) // вторая база на тех же данных
	if игрушка.вызовов != послеПервой {
		t.Errorf("векторы пересчитались заново: было %d вызовов, стало %d", послеПервой, игрушка.вызовов)
	}
}

