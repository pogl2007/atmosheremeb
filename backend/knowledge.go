package main

// Подсказка консультанту по нашим данным (RAG).
//
// Без неё модель отвечала «из общих соображений»: придумывала расшифровку
// незнакомого сокращения и рассказывала про мебель вообще, хотя у нас есть
// конкретный каталог и статьи. Теперь к каждому вопросу подбираются
// подходящие товары и куски статей, и они идут в запрос как справка.
//
// Поиск лексический, без эмбеддингов: 109 товаров и 86 кусков статей — это
// меньше мегабайта, перебор занимает доли миллисекунды. Эмбеддинги добавили бы
// внешний вызов на каждый вопрос, деньги и ещё одну точку отказа.
//
// Ранжирование — BM25: слово, редкое по всей базе, весит больше частого,
// а длинный текст не выигрывает только за счёт длины.

import (
	"context"
	"encoding/json"
	"log"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"time"
	"unicode"
)

const ФайлЗнаний = "knowledge.json"

type ТоварЗнаний struct {
	Имя         string   `json:"имя"`
	Раздел      string   `json:"раздел"`
	Адрес       string   `json:"адрес"`
	Планировка  string   `json:"планировка"`
	Стиль       string   `json:"стиль"`
	Гамма       string   `json:"гамма"`
	Состав      []string `json:"состав"`
	Кратко      string   `json:"кратко"`
	Описание    string   `json:"описание"`
}

type КусокСтатьи struct {
	Статья string `json:"статья"`
	Раздел string `json:"раздел"`
	Адрес  string `json:"адрес"`
	Текст  string `json:"текст"`
}

type знания struct {
	Товары []ТоварЗнаний  `json:"товары"`
	Статьи []КусокСтатьи `json:"статьи"`
}

type запись struct {
	слова  map[string]int // слово → сколько раз
	длина  int
	строка string // что уйдёт в подсказку
	вес    float64
	раздел string // только у товаров
	текст  string // то, что векторизуем
	вектор []float32
}

type База struct {
	папка        string
	векторизатор Векторизатор
	своиВекторы  bool // векторы записей посчитаны

	замок    sync.RWMutex
	путь     string
	изменён  time.Time
	товары   []запись
	статьи   []запись
	средняя  float64
	частоты  map[string]int // в скольких записях встречается слово
	записей  int
}

/* ─────────── Разбор слов ─────────── */

// Окончания режем грубо: полноценная морфология тут не нужна, важно лишь,
// чтобы «кухня», «кухни» и «кухне» считались одним словом.
var окончания = []string{
	"иями", "ями", "ами", "ого", "его", "ему", "ому", "ыми", "ими", "ость",
	"ая", "яя", "ое", "ее", "ые", "ие", "ой", "ей", "ом", "ем", "ах", "ях",
	"ов", "ев", "ью", "ия", "ие", "ий", "ый", "ую", "юю", "ть", "ла", "ло",
	"а", "я", "ы", "и", "е", "у", "ю", "о", "й", "ь",
}

// Слова, которые есть почти в каждом вопросе и ничего не уточняют
var шум = map[string]bool{
	"что": true, "как": true, "где": true, "ваш": true, "мне": true, "мож": true,
	"есть": true, "так": true, "это": true, "или": true, "для": true, "над": true,
	"нужн": true, "хоч": true, "скаж": true, "подскаж": true, "дела": true,
}

func основа(слово string) string {
	слово = strings.ToLower(слово)
	слово = strings.ReplaceAll(слово, "ё", "е")
	руны := []rune(слово)
	if len(руны) < 3 {
		return ""
	}
	for _, о := range окончания {
		if len(руны) > len([]rune(о))+2 && strings.HasSuffix(слово, о) {
			слово = strings.TrimSuffix(слово, о)
			break
		}
	}
	if шум[слово] {
		return ""
	}
	return слово
}

func разобрать(текст string) []string {
	поля := strings.FieldsFunc(текст, func(р rune) bool {
		return !unicode.IsLetter(р) && !unicode.IsDigit(р)
	})
	слова := make([]string, 0, len(поля))
	for _, п := range поля {
		if о := основа(п); о != "" {
			слова = append(слова, о)
		}
	}
	return слова
}

func считать(текст string, вес float64) запись {
	слова := разобрать(текст)
	карта := make(map[string]int, len(слова))
	for _, с := range слова {
		карта[с]++
	}
	return запись{слова: карта, длина: len(слова), вес: вес}
}

/* ─────────── Загрузка ─────────── */

func открытьБазу(папкаДанных string, векторизатор Векторизатор) *База {
	б := &База{путь: filepath.Join(папкаДанных, ФайлЗнаний), папка: папкаДанных, векторизатор: векторизатор}
	if err := б.перечитать(); err != nil {
		log.Printf("справка для консультанта не загружена: %v", err)
	}
	return б
}

// перечитать вызывается при каждом вопросе, но работу делает только если файл
// изменился: после пересборки сайта справка подхватывается без перезапуска.
func (б *База) перечитать() error {
	сведения, err := os.Stat(б.путь)
	if err != nil {
		return err
	}
	б.замок.RLock()
	свежо := сведения.ModTime().Equal(б.изменён) && б.записей > 0
	б.замок.RUnlock()
	if свежо {
		return nil
	}

	сырое, err := os.ReadFile(б.путь)
	if err != nil {
		return err
	}
	var данные знания
	if err := json.Unmarshal(сырое, &данные); err != nil {
		return err
	}

	товары := make([]запись, 0, len(данные.Товары))
	for _, т := range данные.Товары {
		// Имя и раздел повторяем: совпадение по ним важнее совпадения в описании
		полный := т.Имя + " " + т.Имя + " " + т.Раздел + " " + т.Раздел + " " +
			т.Планировка + " " + т.Стиль + " " + т.Гамма + " " +
			strings.Join(т.Состав, " ") + " " + т.Кратко + " " + т.Описание
		з := считать(полный, 1)
		з.строка = "• " + т.Имя + " (" + т.Раздел + ", " + т.Планировка + ", " + т.Стиль +
			", гамма " + т.Гамма + ") — " + т.Кратко + ". В составе: " +
			strings.Join(т.Состав, ", ") + ". Страница: " + т.Адрес
		з.раздел = т.Раздел
		з.текст = т.Имя + ". " + т.Раздел + ". " + т.Кратко + " " + т.Описание
		товары = append(товары, з)
	}

	статьи := make([]запись, 0, len(данные.Статьи))
	for _, к := range данные.Статьи {
		з := считать(к.Статья+" "+к.Раздел+" "+к.Текст, 1)
		з.текст = к.Статья + ". " + к.Раздел + ". " + к.Текст
		з.строка = "• Из статьи «" + к.Статья + "», раздел «" + к.Раздел + "»: " +
			к.Текст + " Ссылка: " + к.Адрес
		статьи = append(статьи, з)
	}

	частоты := map[string]int{}
	всего := 0
	for _, список := range [][]запись{товары, статьи} {
		for _, з := range список {
			всего += з.длина
			for с := range з.слова {
				частоты[с]++
			}
		}
	}

	б.замок.Lock()
	defer б.замок.Unlock()
	б.товары, б.статьи, б.частоты = товары, статьи, частоты
	б.записей = len(товары) + len(статьи)
	if б.записей > 0 {
		б.средняя = float64(всего) / float64(б.записей)
	}
	б.изменён = сведения.ModTime()
	б.своиВекторы = false
	log.Printf("справка консультанта: %d товаров, %d кусков статей", len(товары), len(статьи))

	// Векторы считаются один раз на базу и дальше лежат в файле рядом с ней
	if б.векторизатор != nil {
		тексты := make([]string, 0, len(товары)+len(статьи))
		for _, з := range товары {
			тексты = append(тексты, з.текст)
		}
		for _, з := range статьи {
			тексты = append(тексты, з.текст)
		}
		if векторы, err := посчитатьВекторы(б.векторизатор, б.папка, тексты); err != nil {
			log.Printf("векторный поиск выключен: %v", err)
		} else {
			for i := range б.товары {
				б.товары[i].вектор = векторы[i]
			}
			for i := range б.статьи {
				б.статьи[i].вектор = векторы[len(б.товары)+i]
			}
			б.своиВекторы = true
			log.Printf("векторный поиск включён, модель %s", б.векторизатор.Имя())
		}
	}
	return nil
}

/* ─────────── Согласие ─────────── */

// Короткий ответ клиента, означающий «да, давайте». Длинную реплику сюда не
// пускаем: «да, а сколько стоит шкаф» — это уже вопрос, на него нужна справка.
var словаСогласия = map[string]bool{
	"да": true, "давай": true, "давайте": true, "ага": true, "угу": true, "конечно": true,
	"хорошо": true, "ладно": true, "ок": true, "окей": true, "ok": true, "согласен": true,
	"согласна": true, "можно": true, "жду": true, "подойдет": true, "устраивает": true,
	"пусть": true, "приедет": true, "приезжайте": true, "записывайте": true, "запишите": true,
	"валяй": true, "идет": true,
}

func этоСогласие(вопрос string) bool {
	поля := strings.FieldsFunc(strings.ToLower(strings.ReplaceAll(вопрос, "ё", "е")), func(р rune) bool {
		return !unicode.IsLetter(р) && !unicode.IsDigit(р)
	})
	if len(поля) == 0 || len(поля) > 4 {
		return false
	}
	for _, п := range поля {
		if !словаСогласия[п] {
			return false
		}
	}
	return true
}

