package main

// Подсказка консультанту по нашим данным (RAG).
//
// Без неё модель отвечала «из общих соображений»: придумывала расшифровку
// незнакомого сокращения и рассказывала про мебель вообще, хотя у нас есть
// конкретный каталог и статьи. Теперь к каждому вопросу подбираются
// подходящие товары и куски статей, и они идут в запрос как справка.
//
// Поиск лексический, без эмбеддингов: 109 товаров и 86 кусков статей — это
// меньше мегабайта, перебор занимает доли миллисекунды. Эмбеддинги добавили бы
// внешний вызов на каждый вопрос, деньги и ещё одну точку отказа.
//
// Ранжирование — BM25: слово, редкое по всей базе, весит больше частого,
// а длинный текст не выигрывает только за счёт длины.

import (
	"encoding/json"
	"log"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"time"
	"unicode"
)

const ФайлЗнаний = "knowledge.json"

type ТоварЗнаний struct {
	Имя         string   `json:"имя"`
	Раздел      string   `json:"раздел"`
	Адрес       string   `json:"адрес"`
	Планировка  string   `json:"планировка"`
	Стиль       string   `json:"стиль"`
	Гамма       string   `json:"гамма"`
	Состав      []string `json:"состав"`
	Кратко      string   `json:"кратко"`
	Описание    string   `json:"описание"`
}

type КусокСтатьи struct {
	Статья string `json:"статья"`
	Раздел string `json:"раздел"`
	Адрес  string `json:"адрес"`
	Текст  string `json:"текст"`
}

type знания struct {
	Товары []ТоварЗнаний  `json:"товары"`
	Статьи []КусокСтатьи `json:"статьи"`
}

type запись struct {
	слова  map[string]int // слово → сколько раз
	длина  int
	строка string // что уйдёт в подсказку
	вес    float64
	раздел string // только у товаров
}

type База struct {
	замок    sync.RWMutex
	путь     string
	изменён  time.Time
	товары   []запись
	статьи   []запись
	средняя  float64
	частоты  map[string]int // в скольких записях встречается слово
	записей  int
}

/* ─────────── Разбор слов ─────────── */

// Окончания режем грубо: полноценная морфология тут не нужна, важно лишь,
// чтобы «кухня», «кухни» и «кухне» считались одним словом.
var окончания = []string{
	"иями", "ями", "ами", "ого", "его", "ему", "ому", "ыми", "ими", "ость",
	"ая", "яя", "ое", "ее", "ые", "ие", "ой", "ей", "ом", "ем", "ах", "ях",
	"ов", "ев", "ью", "ия", "ие", "ий", "ый", "ую", "юю", "ть", "ла", "ло",
	"а", "я", "ы", "и", "е", "у", "ю", "о", "й", "ь",
}

// Слова, которые есть почти в каждом вопросе и ничего не уточняют
var шум = map[string]bool{
	"что": true, "как": true, "где": true, "ваш": true, "мне": true, "мож": true,
	"есть": true, "так": true, "это": true, "или": true, "для": true, "над": true,
	"нужн": true, "хоч": true, "скаж": true, "подскаж": true, "дела": true,
}

func основа(слово string) string {
	слово = strings.ToLower(слово)
	слово = strings.ReplaceAll(слово, "ё", "е")
	руны := []rune(слово)
	if len(руны) < 3 {
		return ""
	}
	for _, о := range окончания {
		if len(руны) > len([]rune(о))+2 && strings.HasSuffix(слово, о) {
			слово = strings.TrimSuffix(слово, о)
			break
		}
	}
	if шум[слово] {
		return ""
	}
	return слово
}

func разобрать(текст string) []string {
	поля := strings.FieldsFunc(текст, func(р rune) bool {
		return !unicode.IsLetter(р) && !unicode.IsDigit(р)
	})
	слова := make([]string, 0, len(поля))
	for _, п := range поля {
		if о := основа(п); о != "" {
			слова = append(слова, о)
		}
	}
	return слова
}

func считать(текст string, вес float64) запись {
	слова := разобрать(текст)
	карта := make(map[string]int, len(слова))
	for _, с := range слова {
		карта[с]++
	}
	return запись{слова: карта, длина: len(слова), вес: вес}
}

/* ─────────── Загрузка ─────────── */

func открытьБазу(папкаДанных string) *База {
	б := &База{путь: filepath.Join(папкаДанных, ФайлЗнаний)}
	if err := б.перечитать(); err != nil {
		log.Printf("справка для консультанта не загружена: %v", err)
	}
	return б
}

// перечитать вызывается при каждом вопросе, но работу делает только если файл
// изменился: после пересборки сайта справка подхватывается без перезапуска.
func (б *База) перечитать() error {
	сведения, err := os.Stat(б.путь)
	if err != nil {
		return err
	}
	б.замок.RLock()
	свежо := сведения.ModTime().Equal(б.изменён) && б.записей > 0
	б.замок.RUnlock()
	if свежо {
		return nil
	}

	сырое, err := os.ReadFile(б.путь)
	if err != nil {
		return err
	}
	var данные знания
	if err := json.Unmarshal(сырое, &данные); err != nil {
		return err
	}

	товары := make([]запись, 0, len(данные.Товары))
	for _, т := range данные.Товары {
		// Имя и раздел повторяем: совпадение по ним важнее совпадения в описании
		полный := т.Имя + " " + т.Имя + " " + т.Раздел + " " + т.Раздел + " " +
			т.Планировка + " " + т.Стиль + " " + т.Гамма + " " +
			strings.Join(т.Состав, " ") + " " + т.Кратко + " " + т.Описание
		з := считать(полный, 1)
		з.строка = "• " + т.Имя + " (" + т.Раздел + ", " + т.Планировка + ", " + т.Стиль +
			", гамма " + т.Гамма + ") — " + т.Кратко + ". В составе: " +
			strings.Join(т.Состав, ", ") + ". Страница: " + т.Адрес
		з.раздел = т.Раздел
		товары = append(товары, з)
	}

	статьи := make([]запись, 0, len(данные.Статьи))
	for _, к := range данные.Статьи {
		з := считать(к.Статья+" "+к.Раздел+" "+к.Текст, 1)
		з.строка = "• Из статьи «" + к.Статья + "», раздел «" + к.Раздел + "»: " +
			к.Текст + " Ссылка: " + к.Адрес
		статьи = append(статьи, з)
	}

	частоты := map[string]int{}
	всего := 0
	for _, список := range [][]запись{товары, статьи} {
		for _, з := range список {
			всего += з.длина
			for с := range з.слова {
				частоты[с]++
			}
		}
	}

	б.замок.Lock()
	defer б.замок.Unlock()
	б.товары, б.статьи, б.частоты = товары, статьи, частоты
	б.записей = len(товары) + len(статьи)
	if б.записей > 0 {
		б.средняя = float64(всего) / float64(б.записей)
	}
	б.изменён = сведения.ModTime()
	log.Printf("справка консультанта: %d товаров, %d кусков статей", len(товары), len(статьи))
	return nil
}

/* ─────────── Поиск ─────────── */

// Слова, по которым понятно, о каком разделе каталога речь. Без этого вопрос
// «что за кухни у вас есть» вытягивал прихожие: слово «кухня» частое, а значит
// лёгкое, и его перевешивали совпадения в описаниях других разделов.
var разделПоСлову = []struct {
	признак string
	раздел  string
}{
	{"кухн", "Кухни"}, {"кухон", "Кухни"}, {"гарнитур", "Кухни"},
	{"шкаф", "Шкафы и гардеробные"}, {"купе", "Шкафы и гардеробные"},
	{"гардероб", "Шкафы и гардеробные"}, {"распашн", "Шкафы и гардеробные"},
	{"гостин", "Гостиные"}, {"стенк", "Гостиные"}, {"стеллаж", "Гостиные"},
	{"спальн", "Спальни"}, {"кроват", "Спальни"},
	{"прихож", "Прихожие"}, {"коридор", "Прихожие"},
	{"детск", "Детские"}, {"подростк", "Детские"},
	{"стол", "Столы"},
}

func разделВопроса(вопрос string) string {
	в := strings.ToLower(strings.ReplaceAll(вопрос, "ё", "е"))
	for _, п := range разделПоСлову {
		if strings.Contains(в, п.признак) {
			return п.раздел
		}
	}
	return ""
}

const (
	k1 = 1.5 // насколько сильно повтор слова усиливает совпадение
	b  = 0.6 // насколько штрафуем длинные записи
)

func (б *База) оценить(слова []string, з запись) float64 {
	очки := 0.0
	for _, с := range слова {
		сколько, есть := з.слова[с]
		if !есть {
			continue
		}
		вСкольких := б.частоты[с]
		if вСкольких == 0 {
			continue
		}
		idf := math.Log(1 + (float64(б.записей)-float64(вСкольких)+0.5)/(float64(вСкольких)+0.5))
		норма := float64(сколько) * (k1 + 1) /
			(float64(сколько) + k1*(1-b+b*float64(з.длина)/б.средняя))
		очки += idf * норма
	}
	return очки * з.вес
}

// лучшие отбирает записи, близкие к лучшему совпадению. Порог относительный:
// абсолютный зависел бы от размера базы, и на маленькой подборке отсекал всё.
func (б *База) лучшие(список []запись, слова []string, сколько int, доля float64, раздел string) []string {
	type пара struct {
		очки   float64
		строка string
	}
	найдено := make([]пара, 0, len(список))
	лучшее := 0.0
	for _, з := range список {
		// Раздел назван в вопросе — другие разделы не предлагаем вовсе
		if раздел != "" && з.раздел != "" && з.раздел != раздел {
			continue
		}
		о := б.оценить(слова, з)
		if о <= 0 {
			continue
		}
		if о > лучшее {
			лучшее = о
		}
		найдено = append(найдено, пара{о, з.строка})
	}
	sort.SliceStable(найдено, func(i, j int) bool { return найдено[i].очки > найдено[j].очки })

	// Слабое лучшее совпадение означает, что вопрос вообще не про наши данные
	if лучшее < 0.8 {
		return nil
	}

	строки := make([]string, 0, сколько)
	for _, п := range найдено {
		if len(строки) >= сколько || п.очки < лучшее*доля {
			break
		}
		строки = append(строки, п.строка)
	}
	return строки
}

// Справка — то, что подставляется в запрос к модели. Пусто, если ничего
// подходящего не нашлось: лучше без справки, чем со случайными товарами.
func (б *База) Справка(вопрос string, предыдущие []string) (string, int) {
	if err := б.перечитать(); err != nil {
		return "", 0
	}
	б.замок.RLock()
	defer б.замок.RUnlock()
	if б.записей == 0 {
		return "", 0
	}

	слова := разобрать(вопрос)
	// Прошлые реплики подмешиваем только к совсем короткому вопросу вроде
	// «а подешевле?». Иначе прежняя тема перебивает заданный вопрос —
	// на «я про кухни спросил» консультант продолжал рассказывать про ЛДСП.
	if len(слова) < 2 {
		for _, п := range предыдущие {
			слова = append(слова, разобрать(п)...)
		}
	}
	if len(слова) == 0 {
		return "", 0
	}

	// Половина от лучшего для товаров: подборка должна быть похожей, но не одной
	// моделью. Для статей строже — случайный кусок текста только путает.
	раздел := разделВопроса(вопрос)
	товары := б.лучшие(б.товары, слова, 5, 0.5, раздел)
	статьи := б.лучшие(б.статьи, слова, 2, 0.7, "")
	if len(товары) == 0 && len(статьи) == 0 {
		return "", 0
	}

	var сб strings.Builder
	сб.WriteString("\n\nСПРАВКА ПО НАШИМ ДАННЫМ (подобрана под этот вопрос). " +
		"Опирайся на неё: называй модели по именам и давай ссылку на страницу. " +
		"Если справка не отвечает на вопрос — не выдумывай, скажи, что уточнит менеджер.\n")
	if len(товары) > 0 {
		сб.WriteString("\nПодходящие модели из нашего каталога:\n")
		сб.WriteString(strings.Join(товары, "\n"))
	}
	if len(статьи) > 0 {
		сб.WriteString("\n\nИз наших статей:\n")
		сб.WriteString(strings.Join(статьи, "\n"))
	}
	return сб.String(), len(товары) + len(статьи)
}
